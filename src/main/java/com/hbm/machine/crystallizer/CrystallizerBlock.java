/** Source nine-high dummy assembly, four corner proxies with native power/fluid only. */
public final class CrystallizerBlock extends DummyableBlock {
    private static final MapCodec<CrystallizerBlock> CODEC=simpleCodec(ignored->new CrystallizerBlock());
    public CrystallizerBlock(){super(Properties.of().mapColor(MapColor.METAL).strength(5,6).sound(SoundType.STONE).requiresCorrectToolForDrops().noOcclusion());}
    @Override protected MapCodec<? extends DummyableBlock> codec(){return CODEC;}
    @Override public int[] dimensions(){return new int[]{5,0,1,1,1,1};}
    @Override public int offset(){return 1;}
    @Override public BlockEntity newBlockEntity(BlockPos pos,BlockState state){return isCore(state)?new CrystallizerBlockEntity(pos,state):isPort(state)?new CrystallizerPort(pos,state):null;}
    @Override public <T extends BlockEntity> BlockEntityTicker<T> getTicker(Level level,BlockState state,BlockEntityType<T> type){return isCore(state)?createTickerHelper(type,CrystallizerContent.ENTITY.get(),CrystallizerBlockEntity::tick):null;}
    @Override public void setPlacedBy(Level level,BlockPos pos,BlockState state,LivingEntity placer,ItemStack stack){super.setPlacedBy(level,pos,state,placer,stack);if(level.isClientSide)return;var core=pos.relative(placementFacing(state),-offset());for(var port:CrystallizerBlockEntity.portPositions(core))setPort(level,port,true);}
}